// Theme content for The Fantastical Logic Grid.
//
// Each theme is a small world: a cast and categories with item pools. Its
// story parts live in storylines.js. Item labels are written exactly as they appear on the grid, and
// clue text uses them verbatim (guideline: clue names match grid labels).
//
// Category fields:
//   pos / neg  - predicate templates, {x} is the item label
//   noun       - optional; how questions name the category ("What is Ada's arrival time?")
//   ordinal    - optional; a numbered category that supports ordering clues
//     start, step, count - the value scale (items are a run of consecutive values)
//     label(v)           - grid label for a value
//     less / more        - comparison phrases ("arrived earlier than")
//     lessBy / moreBy    - with an exact gap, {d} is the formatted gap
//     gap(steps)         - formats a gap of `steps` scale steps

export const clock = (startMin) => (v) => {
  const m = startMin + v;
  let h = Math.floor(m / 60) % 24;
  const mm = String(m % 60).padStart(2, '0');
  const ampm = h >= 12 ? 'PM' : 'AM';
  h = h % 12 || 12;
  return `${h}:${mm} ${ampm}`;
};
export const plural = (n, one, many) => `${n} ${n === 1 ? one : many}`;
export const money = (v) => `$${v}`;

