// Echoes of History: real events from the past, retold with a new cast.
//
// Each topic is one true event. The player steps into a situation like it,
// alongside invented characters, never the real people, and untangles who did
// what. On solve, `puzzle.history` tells what really happened, in our own
// words, with a source to read more. Facts were checked against the source
// pages listed with each topic (checked 2026-10-27).
//
// Rules for writing a topic (the tests check the story rules):
//   - Story parts describe a situation like the real one, not the real people:
//     no real names in openings, incidents, mishaps, endings or leads.
//   - The real names, dates and places belong in `history` only.
//   - No story part names a grid item or a cast name (the reader would take
//     it for a clue), and no part uses another topic's cast word.
//   - Every category needs a lead; at least one category is numbered.
//   - `history.summary` is our own wording: two to four plain sentences.
//
// This file imports nothing, so themes.js, storylines.js and topics.js can all
// read it without an import cycle.

const plural = (n, one, many) => `${n} ${n === 1 ? one : many}`;
const clock = (startMin) => (v) => {
  const m = startMin + v;
  let h = Math.floor(m / 60) % 24;
  const mm = String(m % 60).padStart(2, '0');
  const ampm = h >= 12 ? 'PM' : 'AM';
  h = h % 12 || 12;
  return `${h}:${mm} ${ampm}`;
};
const cat = (id, name, pos, neg, items, extra = {}) => ({ id, name, pos, neg, items, ...extra });
const ord = (id, name, pos, neg, o, extra = {}) => ({ id, name, pos, neg, ordinal: o, ...extra });
const timeOrd = (verb, startMin, step) => ({
  start: 0, step, count: 8, label: clock(startMin),
  less: `${verb} earlier than`, more: `${verb} later than`, lessBy: `${verb} {d} earlier than`, moreBy: `${verb} {d} later than`,
  gap: (s) => ((s * step) % 60 === 0 ? plural((s * step) / 60, 'hour', 'hours') : plural(s * step, 'minute', 'minutes')),
});
const ageOrd = (start, step) => ({
  start, step, count: 8, label: (v) => String(v),
  less: 'is younger than', more: 'is older than', lessBy: 'is {d} younger than', moreBy: 'is {d} older than',
  gap: (s) => plural(s * step, 'year', 'years'),
});
const countOrd = (start, step, less, more, lessBy, moreBy, unit, label) => ({
  start, step, count: 8, label: label || ((v) => String(v)), less, more, lessBy, moreBy,
  gap: (s) => plural(s * step, unit[0], unit[1]),
});
const age = (start = 20, step = 5) => ord('age', 'Age', 'is {x} years old', 'is not {x} years old', ageOrd(start, step));

