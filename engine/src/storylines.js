// Number of distinct storylines for a theme with a given goal category.
export function storylineCount(themeId) {
  const s = STORYLINES[themeId];
  const leads = Object.values(s.leads).reduce((n, l) => n + l.length, 0);
  return s.adjs.length * s.openings.length * s.incidents.length * s.mishaps.length * leads * s.endings.length;
}
