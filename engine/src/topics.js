// Topics: the scenario choices under each theme ("Halloween" under Holiday,
// "Museum Heist" under Mystery). A topic shapes everything about a puzzle:
// categories and items, cast, story parts and the art prompt.
//
// Topic fields (all optional except id, name, description, art):
//   cast, names   - replace the theme's cast noun and name pool
//   categories    - list of theme category ids to reuse and/or new category
//                   objects (same shape as in themes.js). Needs at least five,
//                   one of them numbered (ordinal). Default: the theme's own.
//                   { from: 'gear', items: [...] } reuses a theme category
//                   with items that suit the topic (no snorkels at the Pole).
//   story         - a topic with its own story gives every part kind and a
//                   lead for each of its categories, so its stories only ever
//                   talk about its own setting, cast and items (the tests
//                   check this).
//                   Parts: adjs, openings, incidents, mishaps, endings, and
//                   `leads` by category id. Leads may use {one} for the cast
//                   word. No part may name an item or a cast name, since the
//                   reader would take it for a clue.
//   art           - setting: a phrase for picture prompts ("a haunted house at night")
//                   mood: a few words for color and music
// A topic with no story parts uses the theme's own (the theme's "classic" topic).
import { clock, plural, money } from './themes.js';
import { STORYLINES } from './storylines.js';

const cat = (id, name, pos, neg, items, extra = {}) => ({ id, name, pos, neg, items, ...extra });
const ord = (id, name, pos, neg, o, extra = {}) => ({ id, name, pos, neg, ordinal: o, ...extra });
const countOrd = (start, step, label, less, more, lessBy, moreBy, gap) => ({
  start, step, count: 8, label: label || ((v) => String(v)), less, more, lessBy, moreBy, gap,
});
const ageOrd = (start, step) => countOrd(start, step, null, 'is younger than', 'is older than',
  'is {d} younger than', 'is {d} older than', (s) => plural(s * step, 'year', 'years'));
const timeOrd = (verb, startMin, step) => ({
  start: 0, step, count: 8, label: clock(startMin),
  less: `${verb} earlier than`, more: `${verb} later than`, lessBy: `${verb} {d} earlier than`, moreBy: `${verb} {d} later than`,
  gap: (s) => ((s * step) % 60 === 0 ? plural((s * step) / 60, 'hour', 'hours') : plural(s * step, 'minute', 'minutes')),
});

