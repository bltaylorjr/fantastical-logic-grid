export function getTopics(themeId) {
  return TOPICS[themeId] || [];
}

// Pick a topic: a topic id, or 'any' / 'random' / nothing for a random one.
export function resolveTopic(theme, topicId, rng) {
  const list = getTopics(theme.id);
  if (!topicId || topicId === 'any' || topicId === 'random') return rng.pick(list);
  const t = list.find((x) => x.id === topicId);
  if (!t) throw new Error(`Unknown topic "${topicId}" for ${theme.name}. Try one of: any, ${list.map((x) => x.id).join(', ')}`);
  return t;
}

// A topic with no story parts of its own is its theme's classic topic. Its
// storylines are the theme's, so its story ids keep the plain theme key.
export const isClassic = (topic) => !topic.story;
export const storyKey = (theme, topic) => (isClassic(topic) ? theme.id : `${theme.id}/${topic.id}`);

// Everything a puzzle needs from the theme and topic together: cast, names,
// full category objects and the story parts, with the theme filling any gaps.
export function buildScenario(theme, topic) {
  const S = STORYLINES[theme.id];
  const T = topic.story || {};
  const categories = (topic.categories || theme.categories).map((c) => {
    if (typeof c !== 'string' && !c.from) return c;
    const id = typeof c === 'string' ? c : c.from;
    const found = theme.categories.find((x) => x.id === id);
    if (!found) throw new Error(`Topic ${theme.id}/${topic.id} names unknown category "${id}"`);
    if (typeof c === 'string') return found;
    // { from, items }: the theme's category with items that suit this topic.
    const { from, ...over } = c;
    return { ...found, ...over };
  });
  // 'name' is the cast column's id; a topic category must not reuse it.
  if (categories.some((c) => c.id === 'name')) throw new Error(`Topic ${theme.id}/${topic.id} uses the reserved category id "name"`);
  return {
    theme, topic,
    key: storyKey(theme, topic),
    cast: topic.cast || theme.cast,
    names: topic.names || theme.names,
    categories,
    story: {
      adjs: T.adjs || S.adjs,
      openings: T.openings || S.openings,
      incidents: T.incidents || S.incidents,
      mishaps: T.mishaps || S.mishaps,
      endings: T.endings || S.endings,
      leads: { ...S.leads, ...(T.leads || {}) },
    },
    art: topic.art,
  };
}
